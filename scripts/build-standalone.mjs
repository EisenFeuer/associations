// Emits associations.html at the project root: one self-contained file that
// runs from file:// with no server and no network. Run: node scripts/build-standalone.mjs
//
// esbuild bundles src/main.js (Three.js, CSS2DRenderer, and the three web JSON
// files included) into a single classic IIFE script, so no ES module imports or
// fetches remain. style.css is inlined. The Google Fonts link from index.html is
// dropped (it needs the network); the CSS already falls back to system fonts.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  entryPoints: [path.join(root, 'src/main.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  loader: { '.json': 'json' },
  define: { 'import.meta.env.DEV': 'false', 'import.meta.env.PROD': 'true' },
  write: false,
  absWorkingDir: root,
});

// Keep "</script" sequences in string literals from closing the inline tag.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = (await readFile(path.join(root, 'src/style.css'), 'utf8')).replace(/<\/style/gi, '<\\/style');

const html = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Associations</title>
    <!-- Standalone build generated by scripts/build-standalone.mjs. Do not edit by hand. -->
    <style>
${css}
    </style>
  </head>
  <body>
    <div id="app"></div>
    <script>
      window.addEventListener('error', function (e) {
        var pre = document.createElement('pre');
        pre.style.cssText =
          'position:fixed;left:0;right:0;bottom:0;z-index:99;margin:0;padding:10px 14px;background:#3a1010;color:#ffd0d0;font:12px/1.4 ui-monospace,monospace;white-space:pre-wrap';
        pre.textContent = e.message + '\\n' + e.filename + ':' + e.lineno;
        document.body.appendChild(pre);
      });
    </script>
    <script>
${js}
    </script>
  </body>
</html>
`;

const out = path.join(root, 'associations.html');
await writeFile(out, html);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB)`);
